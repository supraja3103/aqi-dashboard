import urllib.request
print("🔑 YOUR PASSWORD IS:", urllib.request.urlopen('https://api.ipify.org').read().decode('utf8'))
print("🚀 Launching Cloudflare Live Link...")
import pandas as pd
import numpy as np
import os
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import LSTM, GRU, Dense, Dropout
from sklearn.preprocessing import MinMaxScaler
from sklearn.metrics import mean_squared_error, mean_absolute_error, r2_score

print("⏳ Step 1 Running: Loading Dataset & Training Deep Learning Models...")

# 1. Load Dataset (city_day.csv check)
csv_file = "city_day.csv"

if os.path.exists(csv_file):
    df = pd.read_csv(csv_file)
    print(f"✅ Found '{csv_file}'! Rows: {len(df)}")
    # Handle missing values & select AQI/PM2.5
    if 'AQI' in df.columns:
        df['AQI'] = df['AQI'].fillna(method='ffill').fillna(method='bfill')
        data = df['AQI'].values.reshape(-1, 1)
    else:
        df['PM2.5'] = df['PM2.5'].fillna(method='ffill').fillna(method='bfill')
        data = df['PM2.5'].values.reshape(-1, 1)
else:
    print(f"⚠️ '{csv_file}' not found in folder. Generating synthetic AQI sample data for training...")
    np.random.seed(42)
    data = np.sin(np.linspace(0, 100, 1000)).reshape(-1, 1) * 50 + 150 + np.random.normal(0, 10, (1000, 1))

# 2. Normalize Data
scaler = MinMaxScaler(feature_range=(0, 1))
scaled_data = scaler.fit_transform(data)

# 3. Create Sequences for Time-Series (Lookback = 10 steps)
def create_dataset(dataset, look_back=10):
    X, Y = [], []
    for i in range(len(dataset) - look_back - 1):
        X.append(dataset[i:(i + look_back), 0])
        Y.append(dataset[i + look_back, 0])
    return np.array(X), np.array(Y)

look_back = 10
X, y = create_dataset(scaled_data, look_back)
X = np.reshape(X, (X.shape[0], X.shape[1], 1))

# Split Train & Test
train_size = int(len(X) * 0.8)
X_train, X_test = X[:train_size], X[train_size:]
y_train, y_test = y[:train_size], y[train_size:]

# 4. Train LSTM Model
print("\n🧠 Training LSTM Model (Model 1)...")
lstm_model = Sequential([
    LSTM(50, return_sequences=True, input_shape=(look_back, 1)),
    Dropout(0.2),
    LSTM(50),
    Dense(1)
])
lstm_model.compile(optimizer='adam', loss='mean_squared_error')
lstm_model.fit(X_train, y_train, epochs=10, batch_size=32, verbose=0)

lstm_preds = lstm_model.predict(X_test, verbose=0)
lstm_preds_orig = scaler.inverse_transform(lstm_preds)
y_test_orig = scaler.inverse_transform(y_test.reshape(-1, 1))

lstm_rmse = np.sqrt(mean_squared_error(y_test_orig, lstm_preds_orig))
lstm_r2 = r2_score(y_test_orig, lstm_preds_orig)
lstm_model.save("lstm_aqi_model.h5")
print(f"✅ LSTM Training Done! | RMSE: {lstm_rmse:.2f} | R² Score: {lstm_r2:.3f}")

# 5. Train GRU Model
print("\n⚡ Training GRU Model (Model 2)...")
gru_model = Sequential([
    GRU(50, return_sequences=True, input_shape=(look_back, 1)),
    Dropout(0.2),
    GRU(50),
    Dense(1)
])
gru_model.compile(optimizer='adam', loss='mean_squared_error')
gru_model.fit(X_train, y_train, epochs=10, batch_size=32, verbose=0)

gru_preds = gru_model.predict(X_test, verbose=0)
gru_preds_orig = scaler.inverse_transform(gru_preds)

gru_rmse = np.sqrt(mean_squared_error(y_test_orig, gru_preds_orig))
gru_r2 = r2_score(y_test_orig, gru_preds_orig)
gru_model.save("gru_aqi_model.h5")
print(f"✅ GRU Training Done!  | RMSE: {gru_rmse:.2f} | R² Score: {gru_r2:.3f}")

print("\n🎉 STEP 1 COMPLETED SUCCESSFULLY!")
print("Saved Model Files: 'lstm_aqi_model.h5' & 'gru_aqi_model.h5'")
